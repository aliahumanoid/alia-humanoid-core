def parse_data(csv_string):
    """Parse CSV string into lists"""
    lines = [l.strip() for l in csv_string.strip().split('\n') if l.strip()]
    time, target, current, error, torque_a, torque_b = [], [], [], [], [], []
    for line in lines:
        parts = line.split(',')
        time.append(float(parts[0]))
        target.append(float(parts[1]))
        current.append(float(parts[2]))
        error.append(float(parts[3]))
        torque_a.append(float(parts[4]))
        torque_b.append(float(parts[5]))
    return {
        'time': time,
        'target': target,
        'current': current,
        'error': error,
        'torque_a': torque_a,
        'torque_b': torque_b
    }


def mean(lst):
    return sum(lst) / len(lst) if lst else 0

def std(lst):
    if len(lst) < 2:
        return 0
    m = mean(lst)
    return math.sqrt(sum((x - m) ** 2 for x in lst) / len(lst))


def analyze(name, data):
    """Calculate metrics for a movement"""
    time = data['time']
    error = data['error']
    torque_a = data['torque_a']
    torque_b = data['torque_b']
    
    duration = time[-1] - time[0]
    
    # Error metrics
    abs_error = [abs(e) for e in error]
    mae = mean(abs_error)
    max_error = max(abs_error)
    error_std = std(error)
    
    # Torque rate of change (jerk)
    d_torque_a = []
    d_torque_b = []
    for i in range(1, len(time)):
        dt = time[i] - time[i-1]
        if dt > 0:
            d_torque_a.append(abs(torque_a[i] - torque_a[i-1]) / dt)
            d_torque_b.append(abs(torque_b[i] - torque_b[i-1]) / dt)
    
    torque_a_jerk = mean(d_torque_a) if d_torque_a else 0
    torque_b_jerk = mean(d_torque_b) if d_torque_b else 0
    torque_a_jerk_max = max(d_torque_a) if d_torque_a else 0
    torque_b_jerk_max = max(d_torque_b) if d_torque_b else 0
    
    # Torque variability
    torque_a_std = std(torque_a)
    torque_b_std = std(torque_b)
    
    print(f"\n{'='*60}")
    print(f"📊 {name}")
    print(f"{'='*60}")
    print(f"⏱️  Durata:           {duration:.3f} s ({len(time)} campioni)")
    print(f"\n📐 ERRORE DI TRACKING:")
    print(f"   MAE:              {mae:.3f}°")
    print(f"   Max |error|:      {max_error:.3f}°")
    print(f"   Std error:        {error_std:.3f}°")
    print(f"\n⚡ COPPIA A (tensione):")
    print(f"   Range:            [{min(torque_a):.0f}, {max(torque_a):.0f}]")
    print(f"   Media:            {mean(torque_a):.1f}")
    print(f"   Std:              {torque_a_std:.1f}")
    print(f"   Jerk medio:       {torque_a_jerk:.1f} /s")
    print(f"   Jerk max:         {torque_a_jerk_max:.1f} /s")
    print(f"\n⚡ COPPIA B (tensione):")
    print(f"   Range:            [{min(torque_b):.0f}, {max(torque_b):.0f}]")
    print(f"   Media:            {mean(torque_b):.1f}")
    print(f"   Std:              {torque_b_std:.1f}")
    print(f"   Jerk medio:       {torque_b_jerk:.1f} /s")
    print(f"   Jerk max:         {torque_b_jerk_max:.1f} /s")
    
    return {
        'duration': duration,
        'mae': mae,
        'max_error': max_error,
        'error_std': error_std,
        'torque_a_std': torque_a_std,
        'torque_b_std': torque_b_std,
        'torque_a_jerk': torque_a_jerk,
        'torque_b_jerk': torque_b_jerk,
        'torque_a_jerk_max': torque_a_jerk_max,
        'torque_b_jerk_max': torque_b_jerk_max,
    }


def compare(single_metrics, multi_metrics, direction):
    """Compare two sets of metrics"""
    print(f"\n{'='*60}")
    print(f"📈 CONFRONTO {direction}")
    print(f"{'='*60}")
    
    def pct_diff(a, b):
        if a == 0:
            return float('inf') if b != 0 else 0
        return ((b - a) / a) * 100
    
    print(f"\n{'Metrica':<25} {'Single WP':<12} {'Multi-WP':<12} {'Diff %':<10}")
    print("-" * 60)
    
    metrics = [
        ('Durata (s)', 'duration'),
        ('MAE (°)', 'mae'),
        ('Max error (°)', 'max_error'),
        ('Error std (°)', 'error_std'),
        ('Torque A std', 'torque_a_std'),
        ('Torque B std', 'torque_b_std'),
        ('Torque A jerk', 'torque_a_jerk'),
        ('Torque B jerk', 'torque_b_jerk'),
        ('Torque A jerk max', 'torque_a_jerk_max'),
        ('Torque B jerk max', 'torque_b_jerk_max'),
    ]
    
    for metric_name, key in metrics:
        s = single_metrics[key]
        m = multi_metrics[key]
        diff = pct_diff(s, m)
        
        if diff < -10:
            symbol = "✅"  # Multi-WP is better (lower values)
        elif diff > 10:
            symbol = "⚠️"  # Multi-WP is worse
        else:
            symbol = "➖"  # Similar
        
        print(f"{metric_name:<25} {s:<12.2f} {m:<12.2f} {diff:>+7.1f}% {symbol}")


